/** Быстрый фильтр каталога: карточка-ссылка на подборку товаров. */
export interface QuickFilter {
  /** Идентификатор фильтра; полезен как `key` в списке. */
  id: string
  /** Путь к картинке для `<NuxtImg>`; фото на белом фоне — оно вписывается в серую подложку. */
  img?: string
  /** Подпись под картинкой, например `Классические`. */
  name: string
  /** Куда ведёт карточка, например `/catalog?style=classic`. */
  to: string
}
